#!/usr/bin/env python3
"""
Voxelization preprocessing for RLBench point cloud dataset.

Expects PLY files generated by rlbench_ply.py:
    root/split/task/all_variations/episodes/episodeN/
        fused_pcd/
            000000.ply
            000001.ply
            ...

Output structure (same level as fused_pcd):
    root/split/task/all_variations/episodes/episodeN/
        voxel_cache/
            manifest.json
            000000_voxels.pt
            000000_meta.pt
            000000_extras.pt
            ...

Usage:
    python preprocess_rlbench_voxels.py --root /path/to/rlbench --splits train --tasks slide_block_to_color_target
    python preprocess_rlbench_voxels.py --root /path/to/rlbench  # Process all
"""

import os
import sys
import argparse
import glob
import json
from tqdm import tqdm

import torch
import numpy as np
import open3d as o3d

# Add parent to path for imports
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from datasets.voxelize_ds_wrapper import VoxelGridXYZ


def safe_tensor(arr, dtype=torch.float32):
    """Convert numpy array to torch tensor without torch.from_numpy() for compatibility."""
    return torch.tensor(arr.tolist(), dtype=dtype)


def read_ply(path: str, include_rgb: bool = True) -> np.ndarray:
    """Read a .ply file with Open3D. Returns [N, 3] or [N, 6] for xyz(+rgb)."""
    pc = o3d.io.read_point_cloud(path)
    xyz = np.asarray(pc.points, dtype=np.float32)
    if include_rgb and len(pc.colors) > 0:
        rgb = np.asarray(pc.colors, dtype=np.float32)
        if rgb.shape[0] == xyz.shape[0]:
            return np.concatenate([xyz, rgb], axis=-1)
    return xyz


def center_scale_unit_cube(pts: np.ndarray) -> np.ndarray:
    """Center and isotropically scale to fit in [-1,1]^3."""
    out = pts.copy()
    xyz = out[:, :3]
    if xyz.shape[0] == 0:
        return out
    mins = xyz.min(axis=0)
    maxs = xyz.max(axis=0)
    center = (mins + maxs) / 2.0
    scale = (maxs - mins).max() + 1e-8
    out[:, :3] = (xyz - center[None, :]) / scale * 2.0
    return out


def discover_episodes(
    root: str,
    splits: list = None,
    tasks: list = None,
) -> list:
    """Discover all episode directories with fused_pcd folders."""
    if splits is None:
        split_dirs = glob.glob(os.path.join(root, "*"))
        splits = [os.path.basename(d) for d in split_dirs if os.path.isdir(d)]

    episodes = []

    for split in splits:
        split_path = os.path.join(root, split)
        if not os.path.isdir(split_path):
            continue

        if tasks is None:
            task_dirs = glob.glob(os.path.join(split_path, "*"))
            task_names = [os.path.basename(d) for d in task_dirs if os.path.isdir(d)]
        else:
            task_names = tasks

        for task in task_names:
            episodes_root = os.path.join(split_path, task, "all_variations", "episodes")
            if not os.path.isdir(episodes_root):
                episodes_root = os.path.join(split_path, task, "episodes")

            if not os.path.isdir(episodes_root):
                continue

            episode_dirs = sorted(
                glob.glob(os.path.join(episodes_root, "episode*")),
                key=lambda x: int(os.path.basename(x).replace("episode", ""))
            )

            # Only include episodes that have fused_pcd folder
            for ep in episode_dirs:
                pcd_dir = os.path.join(ep, "fused_pcd")
                if os.path.isdir(pcd_dir) and len(glob.glob(os.path.join(pcd_dir, "*.ply"))) > 0:
                    episodes.append(ep)

    return episodes


def get_episode_info(episode_dir: str) -> dict:
    """Extract split, task, episode number from path."""
    parts = episode_dir.split(os.sep)

    # Find episode number
    episode_name = os.path.basename(episode_dir)
    episode_num = int(episode_name.replace("episode", ""))

    # Walk backwards to find task and split
    task = None
    split = None
    for i, part in enumerate(reversed(parts)):
        if part == "episodes":
            continue
        if part == "all_variations":
            continue
        if task is None and part not in ["episodes", "all_variations"]:
            task = part
        elif split is None and task is not None:
            split = part
            break

    return {
        "split": split,
        "task": task,
        "episode": episode_num,
    }


def voxelize_episode(
    episode_dir: str,
    grid_whd: tuple = (64, 64, 64),
    voxel_mode: str = "avg_rgb",
    include_rgb: bool = True,
    normalize_to_unit_cube: bool = True,
    max_points: int = None,
    force_rebuild: bool = False,
) -> int:
    """
    Voxelize all frames in a single episode.

    Returns:
        Number of frames voxelized
    """
    pcd_dir = os.path.join(episode_dir, "fused_pcd")
    cache_dir = os.path.join(episode_dir, "voxel_cache")
    manifest_path = os.path.join(cache_dir, "manifest.json")

    # Get PLY files
    ply_files = sorted(glob.glob(os.path.join(pcd_dir, "*.ply")))
    if len(ply_files) == 0:
        return 0

    # Check if already done
    if not force_rebuild and os.path.exists(manifest_path):
        with open(manifest_path, "r") as f:
            mani = json.load(f)
        if mani.get("complete", False) and mani.get("length", 0) >= len(ply_files):
            return 0

    os.makedirs(cache_dir, exist_ok=True)

    # Get episode info
    ep_info = get_episode_info(episode_dir)

    frames_done = 0

    for idx, ply_path in enumerate(ply_files):
        vox_path = os.path.join(cache_dir, f"{idx:06d}_voxels.pt")
        meta_path = os.path.join(cache_dir, f"{idx:06d}_meta.pt")
        extras_path = os.path.join(cache_dir, f"{idx:06d}_extras.pt")

        # Skip if already exists
        if not force_rebuild and os.path.exists(vox_path) and os.path.exists(meta_path):
            frames_done += 1
            continue

        # Read and preprocess
        pts = read_ply(ply_path, include_rgb=include_rgb)
        if pts.shape[0] == 0:
            continue

        if normalize_to_unit_cube:
            pts = center_scale_unit_cube(pts)

        if max_points is not None and pts.shape[0] > max_points:
            idx_sample = np.random.choice(pts.shape[0], max_points, replace=False)
            pts = pts[idx_sample]

        pts_xyz = safe_tensor(pts[:, :3])
        colors = safe_tensor(pts[:, 3:6]) if (pts.shape[-1] >= 6 and voxel_mode == "avg_rgb") else None

        # Voxelize (per-item bounds)
        vg = VoxelGridXYZ(pts_xyz, colors, grid_whd=grid_whd, bounds=None, mode=voxel_mode)
        vox = vg.to_dense().cpu()
        md = vg.meta_dict()
        md_cpu = {k: (v.cpu() if torch.is_tensor(v) else v) for k, v in md.items()}

        # Save
        torch.save(vox, vox_path)
        torch.save(md_cpu, meta_path)

        # Parse frame number from filename
        fname = os.path.basename(ply_path)
        try:
            frame_idx = int(os.path.splitext(fname)[0])
        except ValueError:
            frame_idx = idx

        extras = {
            "path": ply_path,
            "id": os.path.splitext(fname)[0],
            "split": ep_info["split"],
            "task": ep_info["task"],
            "episode": ep_info["episode"],
            "frame": frame_idx,
            "points": pts,
        }
        torch.save(extras, extras_path)
        frames_done += 1

    # Write manifest
    manifest = {
        "split": ep_info["split"],
        "task": ep_info["task"],
        "episode": ep_info["episode"],
        "length": len(ply_files),
        "grid_whd": list(grid_whd),
        "mode": voxel_mode,
        "bounds_mode": "per_item",
        "complete": True,
    }
    with open(manifest_path, "w") as f:
        json.dump(manifest, f, indent=2)

    return frames_done


def main():
    parser = argparse.ArgumentParser(description="Preprocess RLBench point clouds to voxels")
    parser.add_argument("--root", type=str, required=True,
                        help="Root directory of RLBench data")
    parser.add_argument("--splits", type=str, nargs="*", default=None,
                        help="Splits to process (default: all)")
    parser.add_argument("--tasks", type=str, nargs="*", default=None,
                        help="Tasks to process (default: all)")
    parser.add_argument("--grid_whd", type=int, nargs=3, default=[64, 64, 64],
                        help="Voxel grid dimensions (default: 64 64 64)")
    parser.add_argument("--voxel_mode", type=str, default="avg_rgb",
                        choices=["occupancy", "density", "avg_rgb"],
                        help="Voxelization mode (default: avg_rgb)")
    parser.add_argument("--max_points", type=int, default=None,
                        help="Max points per cloud (default: no limit)")
    parser.add_argument("--force", action="store_true",
                        help="Force rebuild even if cache exists")
    parser.add_argument("--no_rgb", action="store_true",
                        help="Don't include RGB (xyz only)")
    parser.add_argument("--no_normalize", action="store_true",
                        help="Don't normalize to unit cube")
    parser.add_argument("--max_episodes", type=int, default=-1,
                        help="Max episodes to process (-1 for all)")

    args = parser.parse_args()

    print(f"Root: {args.root}")
    print(f"Grid: {args.grid_whd}")
    print(f"Mode: {args.voxel_mode}")

    # Discover episodes with PLY files
    episodes = discover_episodes(args.root, args.splits, args.tasks)
    print(f"Found {len(episodes)} episodes with fused_pcd")

    if args.max_episodes > 0:
        episodes = episodes[:args.max_episodes]
        print(f"Processing first {len(episodes)} episodes")

    if len(episodes) == 0:
        print("No episodes with PLY files found!")
        return

    # Process each episode
    total_frames = 0
    for episode_dir in tqdm(episodes, desc="Voxelizing episodes"):
        n_frames = voxelize_episode(
            episode_dir=episode_dir,
            grid_whd=tuple(args.grid_whd),
            voxel_mode=args.voxel_mode,
            include_rgb=not args.no_rgb,
            normalize_to_unit_cube=not args.no_normalize,
            max_points=args.max_points,
            force_rebuild=args.force,
        )
        total_frames += n_frames

    print(f"\nDone! Voxelized {total_frames} frames across {len(episodes)} episodes")


if __name__ == "__main__":
    main()
